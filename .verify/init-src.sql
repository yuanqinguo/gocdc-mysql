CREATE USER IF NOT EXISTS 'root'@'%' IDENTIFIED BY '123456';
GRANT SELECT, REPLICATION SLAVE, REPLICATION CLIENT ON *.* TO 'root'@'%';
GRANT RELOAD, BACKUP_ADMIN ON *.* TO 'root'@'%';

CREATE DATABASE shop;
CREATE TABLE shop.orders (
  id BIGINT NOT NULL AUTO_INCREMENT, user_id BIGINT NOT NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0, remark VARCHAR(255) NULL,
  phone VARCHAR(20) NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE shop.order_items (
  order_id BIGINT NOT NULL, item_no INT NOT NULL,
  product VARCHAR(64) NOT NULL, qty INT NOT NULL DEFAULT 1,
  PRIMARY KEY (order_id, item_no)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE shop.users (
  id BIGINT NOT NULL AUTO_INCREMENT, name VARCHAR(64) NOT NULL,
  phone VARCHAR(20) NULL, created DATETIME NULL,
  PRIMARY KEY (id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE shop.tmp_log (
  id BIGINT NOT NULL AUTO_INCREMENT, msg VARCHAR(64) NULL,
  PRIMARY KEY (id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE DATABASE biz2;
CREATE TABLE biz2.events (
  id BIGINT NOT NULL AUTO_INCREMENT, kind VARCHAR(32) NOT NULL,
  payload VARCHAR(255) NULL,
  PRIMARY KEY (id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE DATABASE types;
CREATE TABLE types.all_types (
  id BIGINT NOT NULL AUTO_INCREMENT,
  c_tiny TINYINT NULL, c_small SMALLINT NULL, c_med MEDIUMINT NULL,
  c_int INT NULL, c_big BIGINT NULL, c_ubig BIGINT UNSIGNED NULL,
  c_dec DECIMAL(12,4) NULL, c_float FLOAT NULL, c_double DOUBLE NULL,
  c_bit BIT(8) NULL, c_char CHAR(10) NULL, c_varchar VARCHAR(64) NULL,
  c_text TEXT NULL, c_blob BLOB NULL, c_varbin VARBINARY(64) NULL,
  c_dt DATETIME(3) NULL, c_ts TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  c_date DATE NULL, c_time TIME NULL, c_year YEAR NULL,
  c_enum ENUM('a','b','c') NULL,
  c_set SET('x','y','z') NULL, c_json JSON NULL,
  PRIMARY KEY (id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
