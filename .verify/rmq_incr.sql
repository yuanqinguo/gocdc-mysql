INSERT INTO rmqtest.msg (name, qty, amount, note)
SELECT CONCAT('inc-', t.N), t.N, t.N * 2.5, CONCAT('inc-note-', t.N)
FROM (SELECT a.N + b.N*10 + 51 N
      FROM (SELECT 0 N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
            UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) a,
           (SELECT 0 N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4) b) t;
UPDATE rmqtest.msg SET qty = qty + 1, note = CONCAT('upd-', id) WHERE id BETWEEN 1 AND 20;
